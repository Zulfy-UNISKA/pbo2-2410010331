    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        // TODO add your handling code here:
        // TODO add your handling code here:
        List<JComponent> salah = new ArrayList<>();
        if (!periksaNpm()) {
            salah.add(npmField);
        }
        if (!periksaNama()) {
            salah.add(namaField);
        }
        if (!periksaProdi()) {
            salah.add(programStudiCombo);
        }
        if (!periksaEmail()) {
            salah.add(emailField);
        }
        if (!periksaHp()) {
            salah.add(hpField);
        }
        if (!salah.isEmpty()) {
            statusLabel.setText(salah.size() + " isian perlu diperbaiki");
            salah.get(0).requestFocusInWindow(); // arahkan pengguna ke kesalahan pertama
            return;
        }

        String anggota = ""; // Default
        for(JRadioButton jRadio : List.of(mahasiswaRadio,dosenRadio,umumRadio)) {
            if(jRadio.isSelected()) {
                anggota = jRadio.getText();
            }
        }
        String pesan =    "NPM: " + npmField.getText()
        + "\nNama Lengkap: "  + namaField.getText()
        + "\nProgram Studi: " + programStudiCombo.getSelectedItem()
        + "\nJenis Anggota: " + anggota
        + "\nEmail: "          + emailField.getText()
        + "\nNomor HP: "       + hpField.getText()
        + "\nAlamat: " + (alamatArea.getText().isEmpty() ?  "-" : alamatArea.getText());
        JOptionPane.showMessageDialog(this, pesan, "Data Pendaftaran Anggota",
            JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_daftarButtonActionPerformed

    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
        // TODO add your handling code here:
        int jawab = JOptionPane.showConfirmDialog(this,
            "Data yang sudah diisi akan dihapus. Lanjutkan?", "Konfirmasi",
            JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (jawab != JOptionPane.YES_OPTION) {
            return;
        }
        for (JTextField isian : List.of(npmField, namaField, emailField, hpField)) {
            isian.setText("");
        }
        npmField.setText("");
        npmPesanLabel.setText("0 dari 10 digit");
        namaField.setText("");
        programStudiCombo.setSelectedIndex(0);
        anggotaButtonGroup.clearSelection();
        emailField.setText("");
        hpField.setText("");
        alamatArea.setText("");
        persetujuanCheckBox.setSelected(false);
        tandai(npmField, npmPesanLabel, null);
        tandai(namaField, namaPesanLabel, null);
        tandai(programStudiCombo, prodiPesanLabel, null);
        tandai(emailField, emailPesanLabel, null);
        tandai(hpField, hpPesanLabel, null);
        statusLabel.setText(" ");
        
        npmField.requestFocusInWindow();
    }//GEN-LAST:event_batalButtonActionPerformed

